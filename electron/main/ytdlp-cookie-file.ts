/**
 * 用户粘贴的 Cookie 头 → yt-dlp 能吃的 Netscape cookiefile（2026-10-21）。
 *
 * 为什么非得落一份文件：`ytdlp-nodejs` 的 `InfoOptions.cookies` 看着像「一串 cookie」，
 * 但它在参数拼装里是 `r.push("--cookies", e.cookies)` —— yt-dlp 的 `--cookies` 收的是
 * **文件路径**，不是头串（`dist/index.js` 实测）。把 `SID=...; HSID=...` 原样递过去，
 * yt-dlp 只会当成一个不存在的路径，最后仍然匿名请求、仍然撞 "Sign in to confirm"。
 * YouTube 的登录态认证（SAPISIDHASH）只从 cookie jar 走，`--add-header Cookie:` 也不作数。
 *
 * 隐私：文件写在系统 temp 下、只用一次就删（`cleanup`），文件名只有平台名 + 随机串，
 * 不含 cookie 值也不含链接；内容不写日志。与 `media-merge` 的合流产物同一条口径。
 */
import { randomBytes } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

/** cookie 有效期给一年：我们拿不到上游真实的 expires，过期后 yt-dlp 会照常重新要登录 */
const EXPIRY_SEC = 60 * 60 * 24 * 365;

export interface CookieFileHandle {
  path: string;
  cleanup: () => Promise<void>;
}

/**
 * `a=1; b=2` + `.youtube.com` → Netscape 文本。
 *
 * 每一行是 7 个制表符分隔的字段（域 / 含子域 / 路径 / 仅 https / 过期 / 名 / 值）。
 * 名字或值里带制表符、换行的条目直接丢掉——那种输入没法安全地表示成一行，
 * 硬塞会把后面的 cookie 挤到别的字段上（等于伪造出一条域/路径）。
 */
export function toNetscapeCookieFile(cookieHeader: string, domain: string, nowMs = Date.now()): string {
  const host = domain.startsWith(".") ? domain : `.${domain}`;
  const expires = Math.floor(nowMs / 1000) + EXPIRY_SEC;
  const lines = ["# Netscape HTTP Cookie File", "# generated by MediaGet; local only, deleted after use"];
  for (const pair of cookieHeader.split(";")) {
    const at = pair.indexOf("=");
    if (at <= 0) continue;
    const name = pair.slice(0, at).trim();
    const value = pair.slice(at + 1).trim();
    if (!name || /[\t\r\n]/.test(`${name}${value}`)) continue;
    lines.push(`${host}\tTRUE\t/\tFALSE\t${expires}\t${name}\t${value}`);
  }
  return `${lines.join("\n")}\n`;
}

/** 文本里到底有没有一条真 cookie（只有两行注释 = 没东西可传，别递给 yt-dlp） */
function hasCookieRows(text: string): boolean {
  return text.split("\n").some((line) => line.length > 0 && !line.startsWith("#"));
}

/**
 * 写临时 cookiefile；`cookieHeader` 里没有可用条目时返回 null（调用方按「没配 Cookie」处理）。
 * 失败（目录不可写等）也返回 null —— 配了 Cookie 却因为写不了文件把整次解析打挂，不划算。
 */
export async function createCookieFile(
  dir: string,
  platform: string,
  cookieHeader: string,
  domain: string
): Promise<CookieFileHandle | null> {
  const text = toNetscapeCookieFile(cookieHeader, domain);
  if (!hasCookieRows(text)) return null;
  try {
    await mkdir(dir, { recursive: true });
    const path = join(dir, `yt-${platform}-${randomBytes(6).toString("hex")}.txt`);
    await writeFile(path, text, { mode: 0o600 });
    return {
      path,
      cleanup: async () => {
        await rm(path, { force: true }).catch(() => undefined);
      },
    };
  } catch {
    return null;
  }
}
